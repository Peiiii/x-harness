import { atomicObservationCode } from "../dist/browser.js";
import { readFileSync, writeFileSync } from "node:fs";
const target = new URL("../generated/observation.mjs", import.meta.url);
const source = `// Generated by scripts/generate-observation.mjs; edit TS reader owners only.\nexport const readXObservation = ${atomicObservationCode};\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source)
    throw new Error("静态观察生成物已过期，请构建 @nextclaw/x-harness");
} else writeFileSync(target, source);
